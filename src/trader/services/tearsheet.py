"""One-page PDF tearsheet and CSV exports (course Topic 4.5 / Lab 19)."""
from __future__ import annotations

import io

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from matplotlib.backends.backend_pdf import PdfPages  # noqa: E402

from trader.core.metrics import METRIC_DEFINITIONS  # noqa: E402
from trader.models import Backtest  # noqa: E402


def _fmt(key: str, v) -> str:
    if v is None:
        return "-"
    f = METRIC_DEFINITIONS.get(key, {}).get("fmt", "num")
    if f == "pct":
        return f"{v:.2%}"
    if f == "int":
        return f"{int(v)}"
    if f == "usd":
        return f"${v:,.0f}"
    if f == "bps":
        return f"{v:.1f} bps"
    return f"{v:.2f}"


def _series(bt: Backtest, key: str) -> pd.Series:
    rows = (bt.series or {}).get(key) or []
    if not rows:
        return pd.Series(dtype=float)
    s = pd.Series([r[1] for r in rows], index=pd.to_datetime([r[0] for r in rows]), dtype=float)
    return s


def pdf(bt: Backtest) -> bytes:
    buf = io.BytesIO()
    with PdfPages(buf) as pp:
        fig = plt.figure(figsize=(11.69, 8.27))
        fig.suptitle(f"Tearsheet - {bt.name}  (backtest #{bt.id}, PAPER / simulated - not investment advice)", fontsize=11,
                     fontweight="bold")
        gs = fig.add_gridspec(3, 3, height_ratios=[1.3, 0.8, 1.1], hspace=0.45, wspace=0.3)
        ax = fig.add_subplot(gs[0, :2])
        eq = _series(bt, "equity")
        ax.plot(eq.index, eq.values, label="Strategy (net)", color="#1f4e79")
        g = _series(bt, "equity_gross")
        if len(g):
            ax.plot(g.index, g.values, label="Strategy (gross)", color="#7f9cc0", ls="--", lw=0.8)
        b = _series(bt, "benchmark")
        if len(b):
            ax.plot(b.index, b.values, label=f"{bt.benchmark} buy & hold", color="#e87122", lw=0.9)
        ax.set_title("Equity vs benchmark (USD)", fontsize=9)
        ax.legend(fontsize=7)
        ax.tick_params(labelsize=7)
        ax2 = fig.add_subplot(gs[1, :2], sharex=ax)
        dd = _series(bt, "drawdown")
        ax2.fill_between(dd.index, dd.values * 100, 0, color="#c0504d", alpha=0.5)
        ax2.set_title("Drawdown (%)", fontsize=9)
        ax2.tick_params(labelsize=7)
        ax3 = fig.add_subplot(gs[2, :2])
        mo = (bt.series or {}).get("monthly") or {}
        if mo.get("values"):
            v = np.array([[np.nan if x is None else x for x in row] for row in mo["values"]], float) * 100
            im = ax3.imshow(v, cmap="RdYlGn", vmin=-8, vmax=8, aspect="auto")
            ax3.set_yticks(range(len(mo["years"])), mo["years"], fontsize=7)
            ax3.set_xticks(range(v.shape[1]), ["J", "F", "M", "A", "M", "J", "J", "A", "S", "O", "N", "D"][: v.shape[1]],
                           fontsize=7)
            for i in range(v.shape[0]):
                for j in range(v.shape[1]):
                    if not np.isnan(v[i, j]):
                        ax3.text(j, i, f"{v[i, j]:.1f}", ha="center", va="center", fontsize=5.5)
            fig.colorbar(im, ax=ax3, shrink=0.8)
        ax3.set_title("Monthly returns (%)", fontsize=9)
        axm = fig.add_subplot(gs[:2, 2])
        axm.axis("off")
        m = bt.metrics or {}
        bm = bt.benchmark_metrics or {}
        keys = ["total_return", "cagr", "volatility", "sharpe", "sortino", "calmar", "max_drawdown", "win_rate",
                "profit_factor", "expectancy", "trades", "exposure", "turnover", "alpha", "beta", "break_even_bps"]
        rows = [[METRIC_DEFINITIONS[k]["label"], _fmt(k, m.get(k)), _fmt(k, bm.get(k)) if k in bm else ""] for k in keys
                if k in METRIC_DEFINITIONS]
        t = axm.table(cellText=rows, colLabels=["Metric", "Strategy", "Benchmark"], loc="upper center", cellLoc="left")
        t.auto_set_font_size(False)
        t.set_fontsize(7)
        t.scale(1, 1.15)
        axc = fig.add_subplot(gs[2, 2])
        axc.axis("off")
        cs = bt.cost_summary or {}
        crow = [[k.replace("_", " "), f"${cs.get(k, 0):,.0f}"] for k in ("commission", "spread", "slippage", "reg_fees", "borrow", "total")
                if k in cs]
        if cs.get("gross_cagr") is not None:
            crow.append(["gross -> net CAGR", f"{cs['gross_cagr']:.2%} -> {cs['net_cagr']:.2%}"])
        if crow:
            tc = axc.table(cellText=crow, colLabels=["Cost", "USD"], loc="upper center", cellLoc="left")
            tc.auto_set_font_size(False)
            tc.set_fontsize(7)
        axc.set_title("Trading costs", fontsize=9)
        fig.text(0.01, 0.01, f"Params {bt.params} | symbols {', '.join(bt.symbols)} | costs "
                 f"{(bt.config or {}).get('costs', {}).get('name', '')} | next-bar execution. Generated by the Quant Trading "
                 "Simulator (Tertiary Infotech Academy course software).", fontsize=6)
        pp.savefig(fig)
        plt.close(fig)
    return buf.getvalue()


def csv_equity(bt: Backtest) -> str:
    df = pd.DataFrame({"equity": _series(bt, "equity"), "equity_gross": _series(bt, "equity_gross"),
                       "benchmark": _series(bt, "benchmark"), "drawdown": _series(bt, "drawdown")})
    df.index.name = "date"
    return df.to_csv()


def csv_trades(bt: Backtest) -> str:
    return pd.DataFrame(bt.trades or []).to_csv(index=False)
